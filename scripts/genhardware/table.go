package main

import (
	"bytes"
	"cmp"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"slices"
	"strconv"

	"github.com/jitllm/jitllm/engine/cost"
)

// entry is one profile of a table as syntax: the composite literal and the
// hardware model and backend it is keyed by.
type entry struct {
	fset      *token.FileSet
	lit       ast.Expr
	name, api string
}

// entries is the profiles of the table src, as syntax.
func entries(src []byte) ([]entry, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		return nil, err
	}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.VAR {
			continue
		}
		for _, sp := range g.Specs {
			vs := sp.(*ast.ValueSpec)
			if len(vs.Names) != 1 || vs.Names[0].Name != "hardware" || len(vs.Values) != 1 {
				continue
			}
			table, ok := vs.Values[0].(*ast.CompositeLit)
			if !ok {
				return nil, fmt.Errorf("genhardware: the table is not a composite literal")
			}
			var out []entry
			for _, e := range table.Elts {
				name, api, err := key(e)
				if err != nil {
					return nil, err
				}
				out = append(out, entry{fset: fset, lit: e, name: name, api: api})
			}
			return out, nil
		}
	}
	return nil, fmt.Errorf("genhardware: no table named hardware")
}

// key is a profile literal's Name and API.
func key(e ast.Expr) (name, api string, err error) {
	lit, ok := e.(*ast.CompositeLit)
	if !ok {
		return "", "", fmt.Errorf("genhardware: a table entry is not a composite literal")
	}
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		k, ok := kv.Key.(*ast.Ident)
		v, isLit := kv.Value.(*ast.BasicLit)
		if !ok || !isLit || v.Kind != token.STRING {
			continue
		}
		s, err := strconv.Unquote(v.Value)
		if err != nil {
			return "", "", err
		}
		switch k.Name {
		case "Name":
			name = s
		case "API":
			api = s
		}
	}
	if name == "" || api == "" {
		return "", "", fmt.Errorf("genhardware: a table entry without a Name and an API")
	}
	return name, api, nil
}

// merge is the table into with each entry of from in place of the entry of
// its hardware model and backend, or beside the others, by name.
func merge(into, from []byte) ([]byte, error) {
	have, err := entries(into)
	if err != nil {
		return nil, err
	}
	add, err := entries(from)
	if err != nil {
		return nil, err
	}
	for _, e := range add {
		i := slices.IndexFunc(have, func(h entry) bool { return h.name == e.name && h.api == e.api })
		if i < 0 {
			have = append(have, e)
			continue
		}
		have[i] = e
	}
	slices.SortFunc(have, func(a, b entry) int { return cmp.Or(cmp.Compare(a.name, b.name), cmp.Compare(a.api, b.api)) })
	var rows bytes.Buffer
	for _, e := range have {
		if err := printer.Fprint(&rows, e.fset, e.lit); err != nil {
			return nil, err
		}
		rows.WriteString(",\n")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s; DO NOT EDIT.\n\npackage cost\n\n", cost.HardwareCommand)
	if len(have) > 0 {
		b.WriteString("import \"github.com/jitllm/jitllm/jit\"\n\n")
	}
	fmt.Fprintf(&b, "var hardware = []Profile{\n%s}\n", rows.Bytes())
	return format.Source(b.Bytes())
}
