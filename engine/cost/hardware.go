package cost

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"reflect"
	"slices"
	"strconv"
	"strings"

	"github.com/jitllm/jitllm/jit"
)

// The hardware table compiled into the engine, and the command that
// measures this machine into it.
const (
	HardwareTable   = "engine/cost/hardware_table.go"
	HardwareCommand = "go run ./scripts/genhardware -probe " + HardwareTable
)

// Known is the profile of hardware model name on backend api in the table.
func Known(name, api string) (Profile, bool) {
	for _, p := range hardware {
		if p.Name == name && p.API == api {
			return p, true
		}
	}
	return Profile{}, false
}

// Hardware is every profile in the table.
func Hardware() []Profile { return slices.Clone(hardware) }

// RenderHardware is the Go source of the table of profiles ps: one entry per
// hardware model and backend, by name, each field that is not zero on a
// line of its own and a device's kind always, numbers to four significant
// figures.
func RenderHardware(ps []Profile) ([]byte, error) {
	ps = slices.Clone(ps)
	slices.SortFunc(ps, func(a, b Profile) int {
		return cmp.Or(cmp.Compare(a.Name, b.Name), cmp.Compare(a.API, b.API))
	})
	for i := 1; i < len(ps); i++ {
		if ps[i].Name == ps[i-1].Name && ps[i].API == ps[i-1].API {
			return nil, fmt.Errorf("cost: two profiles of %s on %s", ps[i].Name, ps[i].API)
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s; DO NOT EDIT.\n\npackage cost\n\n", HardwareCommand)
	if len(ps) > 0 {
		b.WriteString("import \"github.com/jitllm/jitllm/jit\"\n\n")
	}
	b.WriteString("var hardware = []Profile{\n")
	for _, p := range ps {
		b.WriteString(literal(reflect.ValueOf(p), true))
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// literal is v as Go source; elided is set where the type is implied by
// the composite around it.
func literal(v reflect.Value, elided bool) string {
	switch x := v.Interface().(type) {
	case jit.DeviceKind:
		if x == jit.DeviceCPU {
			return "jit.DeviceCPU"
		}
		return "jit.DeviceGPU"
	case float64:
		return strconv.FormatFloat(x, 'g', 4, 64)
	case int64:
		for _, sh := range []int{30, 20, 10} {
			if x >= 1<<sh && x%(1<<sh) == 0 {
				return fmt.Sprintf("%d << %d", x>>sh, sh)
			}
		}
		return strconv.FormatInt(x, 10)
	}
	t := v.Type()
	typ := ""
	if !elided {
		typ = typeName(t)
	}
	switch v.Kind() {
	case reflect.Struct:
		var fields []string
		for i := range t.NumField() {
			f := v.Field(i)
			if f.IsZero() && f.Type() != reflect.TypeFor[jit.DeviceKind]() {
				continue
			}
			fields = append(fields, t.Field(i).Name+": "+literal(f, false))
		}
		return typ + "{\n" + strings.Join(fields, ",\n") + ",\n}"
	case reflect.Array:
		var elems []string
		for i := range v.Len() {
			if e := v.Index(i); !e.IsZero() {
				elems = append(elems, index(t, i)+": "+literal(e, true))
			}
		}
		return typ + "{\n" + strings.Join(elems, ",\n") + ",\n}"
	case reflect.String:
		return strconv.Quote(v.String())
	case reflect.Bool:
		return strconv.FormatBool(v.Bool())
	case reflect.Int:
		return strconv.FormatInt(v.Int(), 10)
	}
	return fmt.Sprintf("%#v", v.Interface())
}

// index is array type t's index i as Go source: a class's name where the
// array is one entry per class.
func index(t reflect.Type, i int) string {
	if t.Len() == int(NumClasses) {
		return classNames[i]
	}
	return strconv.Itoa(i)
}

// typeName is t as this package names it.
func typeName(t reflect.Type) string {
	if t.Kind() == reflect.Array {
		n := strconv.Itoa(t.Len())
		if t.Len() == int(NumClasses) {
			n = "NumClasses"
		}
		return "[" + n + "]" + typeName(t.Elem())
	}
	if t.PkgPath() == reflect.TypeFor[jit.Device]().PkgPath() {
		return "jit." + t.Name()
	}
	return t.Name()
}

// classNames is each class's constant, as the table spells it.
var classNames = [NumClasses]string{"ClassFloat", "ClassSpecial", "ClassInt", "ClassIndex", "ClassLanes", "ClassGroup", "ClassMem"}
